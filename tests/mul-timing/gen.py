#!/usr/bin/env python3
"""Generate the mul-timing microbenchmarks (mul_timing.s + mul_timing_cases.h).

Every benchmark function has the same code shape and only differs in the operand
values it loads from memory, so differences in cycles come from the data alone.
Only caller-saved registers are used, so there is no save/restore overhead.

Questions answered by the generated cases:
  - which operand position matters (rs1 vs rs2, vs2 vs vs1/rs1 for vector)
  - zero shortcut vs. early exit on operand width vs. finer-grained (bit pattern)
  - whether mul, mulw, mulh, mulhu, mulhsu and vmul/vmulh/vmulhu behave alike

Case naming: <kind>_<instr>_<pos>_<value>
  kind  tp  = throughput, 96 independent instructions (8 rotating destinations)
        lat = latency, 48-step dependency chain that keeps the operand values fixed
  pos   which operand carries the varied value; the other one holds FULL
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
FULL = 0x9E3779B97F4A7C15  # dense 64-bit value with the top bit set
SCALAR_OPS = ["mul", "mulw", "mulh", "mulhu", "mulhsu"]
VECTOR_OPS = ["vmul.vv", "vmulh.vv", "vmulhu.vv", "vmul.vx"]
SEWS = [16, 32, 64]
WIDTHS = [4, 8, 12, 16, 20, 24, 31, 32, 33, 40, 48, 56, 63]
N_TP = 96
N_LAT = 48
TP_DESTS = ["t0", "t1", "t2", "t3", "t4", "t5", "a3", "a4"]


def values(bits):
    """Varied operand values for a given operand width, name -> unsigned bit pattern."""
    mask = (1 << bits) - 1
    v = {"zero": 0, "one": 1, "two": 2, "m1": mask}
    for k in WIDTHS:
        if k < bits:
            v[f"d{k}"] = (1 << k) - 1          # dense: k low bits set
            v[f"s{k}"] = 1 << k                # sparse: single bit at position k
            v[f"n{k}"] = (-(1 << k)) & mask    # negative: -2^k (leading ones)
    v["top"] = 1 << (bits - 1)
    v["max"] = (1 << (bits - 1)) - 1
    v["p55"] = int("55" * (bits // 8), 16)
    v["pAA"] = int("AA" * (bits // 8), 16)
    v["full"] = FULL & mask
    return v


def ident(s):
    return s.replace(".", "_")


asm, cases = [], []


def func(name, body, data):
    cases.append(name)
    asm.append(f".data\n.align 3\n{name}_ops:\n" + "".join(f"  .dword 0x{d:016x}\n" for d in data))
    asm.append(f".text\n.globl {name}\n.align 2\n{name}:\n" + body + "    ret\n")


SCALAR_LOAD = "    la t6, {n}_ops\n    ld a1, 0(t6)\n    ld a2, 8(t6)\n"

# Baselines (same setup, no measured instructions)
func("base_scalar", SCALAR_LOAD.format(n="base_scalar"), [0, 0])
for sew in SEWS:
    n = f"base_vec_e{sew}"
    func(n, SCALAR_LOAD.format(n=n) + f"    vsetivli zero, {128 // sew}, e{sew}, m1, ta, ma\n"
         "    vmv.v.x v1, a1\n    vmv.v.x v2, a2\n", [0, 0])

# Latency reference: same chain with a 1-cycle add instead of a multiply
def lat_body(op, varied_first):
    srcs = "a5, a2" if varied_first else "a2, a5"
    step = f"      {op} t0, {srcs}\n      andi t1, t0, 0\n      or a5, a1, t1\n"
    return f"    mv a5, a1\n    .rept {N_LAT}\n{step}    .endr\n"


n = "lat_add_rs1_full"
func(n, SCALAR_LOAD.format(n=n) + lat_body("add", True), [FULL, FULL])

# Scalar multiplies: a1 = varied value, a2 = FULL
for op in SCALAR_OPS:
    for vname, val in values(64).items():
        for pos, varied_first in (("rs1", True), ("rs2", False)):
            srcs = "a1, a2" if varied_first else "a2, a1"
            n = f"tp_{op}_{pos}_{vname}"
            body = "".join(f"      {op} {d}, {srcs}\n" for d in TP_DESTS)
            func(n, SCALAR_LOAD.format(n=n) + f"    .rept {N_TP // len(TP_DESTS)}\n{body}    .endr\n",
                 [val, FULL])
            n = f"lat_{op}_{pos}_{vname}"
            func(n, SCALAR_LOAD.format(n=n) + lat_body(op, varied_first), [val, FULL])

# Vector multiplies: v1 = varied value (broadcast), v2 = FULL (broadcast); a1/a2 for .vx
for sew in SEWS:
    vsetup = (f"    vsetivli zero, {128 // sew}, e{sew}, m1, ta, ma\n"
              "    vmv.v.x v1, a1\n    vmv.v.x v2, a2\n")
    for op in VECTOR_OPS:
        if op == "vmul.vx":
            positions = (("vs2", "v1, a2"), ("rs1", "v2, a1"))
        else:
            positions = (("vs2", "v1, v2"), ("vs1", "v2, v1"))
        for vname, val in values(sew).items():
            for pos, srcs in positions:
                n = f"tp_{ident(op)}_e{sew}_{pos}_{vname}"
                body = "".join(f"      {op} v{8 + i}, {srcs}\n" for i in range(8))
                func(n, SCALAR_LOAD.format(n=n) + vsetup + f"    .rept {N_TP // 8}\n{body}    .endr\n",
                     [val, FULL & ((1 << sew) - 1)])

with open(os.path.join(HERE, "mul_timing.s"), "w") as f:
    f.write("// Generated by gen.py -- do not edit\n" + "\n".join(asm))
with open(os.path.join(HERE, "mul_timing_cases.h"), "w") as f:
    f.write("// Generated by gen.py -- do not edit\n#ifndef MUL_TIMING_CASES_H\n#define MUL_TIMING_CASES_H\n")
    f.write("".join(f"extern void {c}(void);\n" for c in cases))
    f.write("static const struct { const char *name; void (*fn)(void); } mul_timing_cases[] = {\n")
    f.write("".join(f'  {{"{c}", {c}}},\n' for c in cases))
    f.write("};\n#endif\n")
print(f"{len(cases)} cases")
